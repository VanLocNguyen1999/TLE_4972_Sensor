float maths_sqrt_of_susq_lut(const float a, const float b, const float max)
{
	float one_per_max = 1.0 / max;
	float a2_add_b2_percent = ( a*a + b*b ) * one_per_max * one_per_max;
	a2_add_b2_percent *= 256;
	if (a2_add_b2_percent > 256){
		a2_add_b2_percent = 256;
	}else if (a2_add_b2_percent < 0){
		a2_add_b2_percent = 0;
	}
	uint16_t index = (uint16_t) a2_add_b2_percent;
	float result = max * sqrt_tbl[index];
	return result;
}
float maths_sqrt_of_susq_binary(const float a, const float b)
{
	float temp = a*a + b*b;
	temp = maths_sqrt_binary(temp);
	return temp;
}
